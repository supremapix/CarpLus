import assert from 'node:assert/strict';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { getPaginationRedirects, analyzePagination } from '../src/lib/seoIndexing';
import { getStaticRoutes } from './static-routes';
import { CUSTOMER_ROUTES } from './essential-customer-routes';

const config = JSON.parse(fs.readFileSync('vercel.json', 'utf8'));
assert.deepEqual(config.headers.find((rule: any) => rule.source === '/build-info.json')?.headers, [{ key: 'Cache-Control', value: 'no-store' }]);
const baseline = JSON.parse(execFileSync('git', ['show', 'fb6ade57b438b3b3ab799edd3423439c3db19851:vercel.json'], { encoding: 'utf8' }));
const pagination = (r: any) => r.source === '/pneus' && r.has?.some((h: any) => h.type === 'query' && h.key === 'page');
assert.equal(baseline.redirects.filter(pagination).length, 76);
assert.deepEqual(config.redirects, baseline.redirects.filter((r: any) => !pagination(r)), 'All manual redirects preserved in original order');
assert.deepEqual(config.rewrites, baseline.rewrites, 'All rewrites unchanged');
assert.deepEqual(getPaginationRedirects(), [], 'No catalog page may redirect to a different catalog selection');
assert.ok(analyzePagination().every(page => page.robots === 'noindex,follow' && !page.redirect));
const currentRoutes = getStaticRoutes();
const editorialAdditions = ['/blog/pneus-carros-eletricos-duvidas-curitiba', '/blog/pneu-eletrico-furado-tpms-orcamento', '/suspensao-4x4-curitiba'];
const preservedRoutes = currentRoutes.filter(route => !editorialAdditions.includes(route.path));
assert.equal(currentRoutes.length, 1536, 'Original inventory plus exactly two editorial routes and the suspension catalog');
assert.equal(preservedRoutes.length, 1533, 'Original inventory preserved');
const baselineUrls = ['sitemap-produtos.xml', 'sitemap-medidas.xml', 'sitemap-veiculos.xml', 'sitemap-servicos.xml'].flatMap(file => [...execFileSync('git', ['show', `fb6ade57b438b3b3ab799edd3423439c3db19851:public/${file}`], { encoding: 'utf8' }).matchAll(/<loc>(.*?)<\/loc>/g)].map(match => match[1]));
assert.deepEqual(preservedRoutes.map(route => route.expectedCanonical).sort(), baselineUrls.sort(), 'Exact sitemap URL identities preserved');
assert.equal(CUSTOMER_ROUTES.length, 64);
assert.equal(new Set(CUSTOMER_ROUTES.map(r => r.path)).size, 64);
const applies = (query: Record<string, string>) => config.headers.filter((rule: any) => rule.source === '/pneus' && rule.has?.every((condition: any) => query[condition.key] !== undefined && new RegExp(`^(?:${condition.value})$`).test(query[condition.key]))).some((rule: any) => rule.headers.some((h: any) => h.key === 'X-Robots-Tag' && h.value === 'noindex, follow'));
assert.equal(applies({}), false);
assert.equal(applies({ page: '1' }), false);
assert.equal(applies({ q: '' }), false);
assert.equal(applies({ q: '   ' }), false);
assert.equal(applies({ q: 'michelin' }), true);
assert.equal(applies({ page: '2' }), true);
assert.equal(applies({ page: '20' }), true);
for (const key of ['marca', 'aro', 'largura', 'altura']) assert.equal(applies({ [key]: '15' }), true);
const shell = fs.readFileSync('index.html', 'utf8');
assert.equal([...shell.matchAll(/property="og:image"/g)].length, 1);
for (const asset of ['favicon.svg', 'favicon-96x96.png', 'favicon.ico', 'apple-touch-icon.png', 'site.webmanifest', 'og-carplus.webp']) assert.ok(fs.existsSync(`public/${asset}`), asset);
console.log('Suprema SEO: catalog pagination, query headers, manual routing, 1533 sitemap URLs, 64 customer/service routes and share assets passed.');

const catalogSource = fs.readFileSync('src/components/TireCatalog.tsx', 'utf8');
assert.ok(!/<Navigate\b|REDIRECT_THRESHOLD|shouldRedirect/.test(catalogSource), 'Catalog must not independently redirect paginated selections in the SPA');
assert.ok(catalogSource.includes('Página ${safePage}'), 'Pagination has its own contextual title');
assert.ok(fs.readFileSync('scripts/build-deploy.mjs', 'utf8').includes("run('npm run test:catalog-pagination:browser', { essential: true })"), 'Actual browser pagination is a required publication gate');
